HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from data_access import REPO_ROOT, Dashboard  # noqa: E402

_WORKFLOW = {}


def get_workflow(dash: Dashboard):
    """Lazily create the workflow object (imports the SSR code only when the demonstration is first used)."""
    key = str(dash.root)
    if key not in _WORKFLOW:
        from workflow import Workflow
        _WORKFLOW[key] = Workflow(dash.root)
    return _WORKFLOW[key]


STARTED_AT = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
GET_ROUTES = ["/api/overview", "/api/personas", "/api/responses", "/api/coverage", "/api/validation", "/api/limitations",
              "/api/workflow/options", "/api/response", "/api/health",
              "/api/survey/batches", "/api/survey/batch", "/api/survey/saved", "/api/survey/job", "/api/survey/export", "/api/simple/options", "/api/product/options",
              "/api/evaluation/options", "/api/evaluation/saved", "/api/evaluation/export"]
POST_ROUTES = ["/api/product/respond", "/api/product/report", "/api/simple/run", "/api/survey/generate", "/api/workflow/step/1", "/api/workflow/step/2", "/api/workflow/step/3", "/api/workflow/step/4", "/api/workflow/step/5", "/api/workflow/step/6", "/api/evaluation/run"]


class DashboardServer(ThreadingHTTPServer):
    """Refuses to share its port. The stock HTTPServer enables address reuse, which on Windows lets a SECOND dashboard process bind the
    same port; requests are then split between the old and the new process and routes added later answer 404 on the old one."""
    allow_reuse_address = False

    def server_bind(self):
        if hasattr(socket, "SO_EXCLUSIVEADDRUSE"):
            self.socket.setsockopt(socket.SOL_SOCKET, socket.SO_EXCLUSIVEADDRUSE, 1)
        super().server_bind()


_BATCHES = {}
_PRODUCT = {}
_EVALUATION = {}


def get_evaluation_service(dash: Dashboard):
    key = str(dash.root)
    if key not in _EVALUATION:
        from evaluation_service import ProductEvaluationService
        _EVALUATION[key] = ProductEvaluationService(dash.root)
    return _EVALUATION[key]


def get_product(dash: Dashboard):
    key = str(dash.root)
    if key not in _PRODUCT:
        from product_research import ProductResearch
        _PRODUCT[key] = ProductResearch(get_workflow(dash))
    return _PRODUCT[key]


def get_batches(dash: Dashboard):
    key = str(dash.root)
    if key not in _BATCHES:
        from survey_batches import BatchManager
        _BATCHES[key] = BatchManager(get_workflow(dash))
    return _BATCHES[key]


def survey_export(dash: Dashboard, query: dict):
    """Returns (status, body bytes, content type, filename|None) for CSV/JSON export of a saved batch or of the saved pilot responses."""
    from survey_batches import export_rows, to_csv
    fmt = (query.get("format") or ["csv"])[0]
    src = (query.get("source") or ["batch"])[0]
    if fmt not in ("csv", "json") or src not in ("batch", "saved"):
        return HTTPStatus.BAD_REQUEST, json.dumps({"error": "format must be csv or json; source must be batch or saved"}).encode(), "application/json", None
    if src == "batch":
        bid = (query.get("id") or [""])[0]
        b = get_batches(dash).get_batch(bid) if bid else None
        if b is None:
            return HTTPStatus.BAD_REQUEST if not bid else HTTPStatus.NOT_FOUND, json.dumps({"error": "parameter 'id' must name a saved batch"}).encode(), "application/json", None
        rows, name = export_rows(b["items"], b["batch_id"]), f"synthetic_survey_responses_{b['batch_id']}"
    else:
        sv = get_batches(dash).saved_pilot((query.get("encoder") or ["local_bge_base"])[0])
        rows, name = export_rows(sv.get("items", []), "saved_pilot"), "saved_pilot_synthetic_survey_responses"
    if fmt == "json":
        return HTTPStatus.OK, json.dumps(rows, indent=2, allow_nan=False, default=str).encode("utf-8"), "application/json; charset=utf-8", name + ".json"
    return HTTPStatus.OK, to_csv(rows).encode("utf-8"), "text/csv; charset=utf-8", name + ".csv"


STATIC = HERE / "static"
MAX_BODY = 64 * 1024
STATIC_FILES = {"/": "index.html", "/index.html": "index.html", "/app.js": "app.js", "/styles.css": "styles.css"}
TYPES = {".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8"}


def route(dash: Dashboard, path: str, query: dict):
    """Return (status, payload) for an /api path. Pure function so it can be tested without a socket."""
    api = {"/api/overview": dash.overview, "/api/personas": dash.personas, "/api/responses": dash.responses,
           "/api/coverage": dash.coverage, "/api/validation": dash.validation, "/api/limitations": dash.limitations}
    if path in api:
        return HTTPStatus.OK, api[path]()
    if path == "/api/health":
        return HTTPStatus.OK, {"app": "digital-persona-dashboard", "pid": os.getpid(), "server_started_utc": STARTED_AT,
                               "get_routes": GET_ROUTES, "post_routes": POST_ROUTES}
    if path == "/api/evaluation/options":
        try:
            return HTTPStatus.OK, get_evaluation_service(dash).options()
        except Exception as e:
            return HTTPStatus.OK, {"available": False, "error": f"Could not load evaluation options ({type(e).__name__})."}
    if path == "/api/evaluation/saved":
        eid = (query.get("id") or ["nova_ai_smartphone"])[0]
        data = get_evaluation_service(dash).load_evaluation(eid)
        return (HTTPStatus.OK, data) if data else (HTTPStatus.NOT_FOUND, {"error": f"Evaluation '{eid}' not found"})
    if path == "/api/product/options":
        try:
            return HTTPStatus.OK, get_product(dash).options()
        except Exception as e:
            return HTTPStatus.OK, {"available": False, "error": f"Could not load the personas ({type(e).__name__})."}
    if path == "/api/simple/options":
        try:
            return HTTPStatus.OK, get_workflow(dash).simple_options()
        except Exception as e:
            return HTTPStatus.OK, {"available": False, "error": f"Could not load the personas ({type(e).__name__})."}
    if path == "/api/workflow/options":
        try:
            from survey_batches import MAX_PER_BATCH
            return HTTPStatus.OK, {**get_workflow(dash).options(), "survey_max_per_batch": MAX_PER_BATCH}
        except Exception as e:
            return HTTPStatus.OK, {"available": False, "error": f"Workflow could not be initialised ({type(e).__name__})."}
    if path.startswith("/api/survey/"):
        q1 = lambda k: (query.get(k) or [""])[0]
        if path == "/api/survey/export":       # the real export is streamed as a file download by the request handler
            return HTTPStatus.BAD_REQUEST, {"error": "use /api/survey/export?source=batch&id=<batch>&format=csv|json"}
        if path == "/api/survey/batches":
            return HTTPStatus.OK, {"batches": get_batches(dash).list_batches()}
        if path == "/api/survey/saved":
            return HTTPStatus.OK, get_batches(dash).saved_pilot(q1("encoder") or "local_bge_base")
        if path == "/api/survey/batch":
            if not q1("id"):
                return HTTPStatus.BAD_REQUEST, {"error": "parameter 'id' is required"}
            b = get_batches(dash).get_batch(q1("id"))
            return (HTTPStatus.OK, b) if b else (HTTPStatus.NOT_FOUND, {"error": "no such batch"})
        if path == "/api/survey/job":
            if not q1("id"):
                return HTTPStatus.BAD_REQUEST, {"error": "parameter 'id' is required"}
            j = get_batches(dash).job(q1("id"))
            return (HTTPStatus.OK, j) if j else (HTTPStatus.NOT_FOUND, {"error": "no such job"})
    if path == "/api/response":
        src, sid = (query.get("source") or [""])[0], (query.get("id") or [""])[0]
        if not src or not sid:
            return HTTPStatus.BAD_REQUEST, {"error": "parameters 'source' and 'id' are required"}
        d = dash.response_detail(src, sid)
        if d is None:
            return HTTPStatus.NOT_FOUND, {"error": "no such response in the saved dataset"}
        return HTTPStatus.OK, d
    return HTTPStatus.NOT_FOUND, {"error": "unknown endpoint"}


def make_handler(dash: Dashboard):
    class Handler(BaseHTTPRequestHandler):
        server_version = "DigitalPersonaDashboard"

        def _send(self, status, body: bytes, ctype: str):
            self.send_response(status)
            self.send_header("Content-Type", ctype)
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", "no-store")
            self.send_header("X-Content-Type-Options", "nosniff")
            self.end_headers()
            self.wfile.write(body)

        def do_GET(self):
            u = urlparse(self.path)
            if u.path == "/api/evaluation/export":
                q = parse_qs(u.query)
                eid = (q.get("id") or ["nova_ai_smartphone"])[0]
                fmt = (q.get("format") or ["json"])[0]
                try:
                    body, ctype, fname = get_evaluation_service(dash).export_data(eid, fmt)
                    self.send_response(HTTPStatus.OK)
                    self.send_header("Content-Type", ctype)
                    self.send_header("Content-Length", str(len(body)))
                    self.send_header("Content-Disposition", f'attachment; filename="{fname}"')
                    self.end_headers()
                    self.wfile.write(body)
                    return
                except Exception as e:
                    return self._send(HTTPStatus.BAD_REQUEST, json.dumps({"error": str(e)}).encode("utf-8"), "application/json; charset=utf-8")
            if u.path == "/api/survey/export":
                try:
                    status, body, ctype, fname = survey_export(dash, parse_qs(u.query))
                except Exception as e:
                    status, body, ctype, fname = HTTPStatus.INTERNAL_SERVER_ERROR, json.dumps({"error": type(e).__name__}).encode(), "application/json", None
                self.send_response(status)
                self.send_header("Content-Type", ctype)
                self.send_header("Content-Length", str(len(body)))
                if fname:
                    self.send_header("Content-Disposition", f'attachment; filename="{fname}"')
                self.end_headers()
                self.wfile.write(body)
                return
            if u.path.startswith("/api/"):
                try:
                    status, payload = route(dash, u.path, parse_qs(u.query))
                    body = json.dumps(payload, allow_nan=False).encode("utf-8")
                except Exception as e:  # a bad output file must never crash the server
                    status, body = HTTPStatus.INTERNAL_SERVER_ERROR, json.dumps({"error": f"{type(e).__name__} while reading outputs"}).encode("utf-8")
                return self._send(status, body, "application/json; charset=utf-8")
            if u.path == "/favicon.ico":                       # browsers request it automatically; answer quietly instead of logging a 404
                return self._send(HTTPStatus.NO_CONTENT, b"", "image/x-icon")
            name = STATIC_FILES.get(u.path)
            if not name or not (STATIC / name).exists():
                return self._send(HTTPStatus.NOT_FOUND, b"Not found", "text/plain; charset=utf-8")
            return self._send(HTTPStatus.OK, (STATIC / name).read_bytes(), TYPES[Path(name).suffix])

        def do_POST(self):
            """Only the demonstration steps accept POST. A cross-site page cannot trigger them: foreign Origins are refused."""
            u = urlparse(self.path)
            m = re.fullmatch(r"/api/workflow/step/([1-6])", u.path)
            if not m and u.path not in ("/api/survey/generate", "/api/simple/run", "/api/product/respond", "/api/product/report", "/api/evaluation/run"):
                return self._send(HTTPStatus.METHOD_NOT_ALLOWED, b"Read-only dashboard", "text/plain; charset=utf-8")
            origin = self.headers.get("Origin")
            host = self.headers.get("Host", "")
            if origin and origin not in (f"http://{host}", f"http://127.0.0.1:{self.server.server_address[1]}", f"http://localhost:{self.server.server_address[1]}"):
                return self._send(HTTPStatus.FORBIDDEN, json.dumps({"error": "cross-origin request refused"}).encode("utf-8"), "application/json; charset=utf-8")
            try:
                length = int(self.headers.get("Content-Length", "0"))
                if length > MAX_BODY:
                    raise ValueError("body too large")
                body = json.loads(self.rfile.read(length) or b"{}")
                if not isinstance(body, dict):
                    raise ValueError("body must be a JSON object")
            except Exception:
                return self._send(HTTPStatus.BAD_REQUEST, json.dumps({"ok": False, "error": "invalid JSON request"}).encode("utf-8"), "application/json; charset=utf-8")
            try:
                if u.path == "/api/evaluation/run":
                    payload = get_evaluation_service(dash).run_evaluation(body)
                elif u.path == "/api/product/respond":
                    payload = get_product(dash).respond(body)
                elif u.path == "/api/product/report":
                    payload = get_product(dash).report(body)
                elif u.path == "/api/simple/run":
                    payload = get_workflow(dash).simple_run(body)
                else:
                    payload = get_batches(dash).start(body) if m is None else get_workflow(dash).run_step(int(m.group(1)), body)
                data = json.dumps(payload, allow_nan=False).encode("utf-8")
                status = HTTPStatus.OK
            except Exception as e:
                import traceback
                traceback.print_exc()
                status, data = HTTPStatus.INTERNAL_SERVER_ERROR, json.dumps({"ok": False, "error": f"{str(e)} ({type(e).__name__})"}).encode("utf-8")
            return self._send(status, data, "application/json; charset=utf-8")

        def do_PUT(self):
            self._send(HTTPStatus.METHOD_NOT_ALLOWED, b"Read-only dashboard", "text/plain; charset=utf-8")

        do_DELETE = do_PATCH = do_PUT

        def log_message(self, fmt, *args):
            sys.stderr.write("[dashboard] " + (fmt % args) + "\n")

    return Handler


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--port", type=int, default=8765)
    ap.add_argument("--root", default=str(REPO_ROOT))
    a = ap.parse_args(argv)
    dash = Dashboard(a.root)
    try:
        srv = DashboardServer(("127.0.0.1", a.port), make_handler(dash))
    except OSError as e:
        print(f"Could not start on port {a.port}: {e}")
        print("Another program (possibly an older dashboard window) is already using this port.")
        print("Close that window, or stop every old dashboard server with this PowerShell command:")
        print("  Get-CimInstance Win32_Process -Filter \"Name='python.exe'\" | Where-Object { $_.CommandLine -match 'dashboard' } | ForEach-Object { Stop-Process -Id $_.ProcessId -Force }")
        print("or start this one on another port:  python dashboard\\server.py --port 8766")
        return 1
    print(f"Digital Persona dashboard: http://127.0.0.1:{a.port}   (pid {os.getpid()}, reading {Path(a.root).resolve()})\nPress Ctrl+C to stop.")
    try:
        srv.serve_forever()
    except KeyboardInterrupt:
        print("\nStopped.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
