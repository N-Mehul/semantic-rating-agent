"""Local read-only dashboard server (Python standard library only; no extra dependencies).

Windows CMD, from anywhere:   python dashboard\\server.py            then open  http://127.0.0.1:8765
Options:  --port 8765   --root <repository root>   (binds to 127.0.0.1 only; GET requests only)

The server reads the saved pipeline outputs through dashboard/data_access.py on every request. The "Workflow" page can run the
six-step demonstration through dashboard/workflow.py: scoring an existing saved response, or (only after an explicit, confirmed
click and only if a backend is configured) generating one new response. Nothing is generated by loading a page; no key is exposed.
"""
